create function private.is_owner() returns boolean
language sql stable security definer set search_path = ''
as $$ select exists (
  select 1 from public.staff_roles
  where user_id = (select auth.uid()) and role = 'owner'
) $$;

create function private.is_barber_for(p_barber_id uuid) returns boolean
language sql stable security definer set search_path = ''
as $$ select exists (
  select 1 from public.barbers b
  join public.staff_roles r on r.user_id = b.user_id and r.role = 'barber'
  where b.id = p_barber_id and b.user_id = (select auth.uid())
) $$;

create function private.promotion_eligible(p_promotion_id uuid) returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1
    from public.promotions p
    join public.loyalty_accounts l on l.client_id = (select auth.uid())
    where p.id = p_promotion_id
      and p.active
      and now() between p.starts_at and p.ends_at
      and (p.min_rank_id is null or l.rank_id >= p.min_rank_id)
      and l.visits >= p.min_visits
      and (p.max_visits is null or l.visits <= p.max_visits)
      and l.points_total >= p.min_points
      and (p.inactive_days is null or (
        l.last_visit_at is not null
        and l.last_visit_at <= now() - make_interval(days => p.inactive_days)
      ))
  )
$$;


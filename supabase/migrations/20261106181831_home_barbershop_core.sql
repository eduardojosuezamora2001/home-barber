create schema if not exists private;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text unique,
  full_name text not null default '',
  phone text,
  created_at timestamptz not null default now()
);

create table public.staff_roles (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  role text not null check (role in ('owner', 'barber'))
);

create table public.ranks (
  id integer generated by default as identity primary key,
  name text not null unique,
  min_visits integer not null unique check (min_visits >= 0),
  description text not null default ''
);

create table public.loyalty_accounts (
  client_id uuid primary key references public.profiles(id) on delete cascade,
  visits integer not null default 0 check (visits >= 0),
  points_total integer not null default 0 check (points_total >= 0),
  rank_id integer references public.ranks(id),
  last_visit_at timestamptz,
  updated_at timestamptz not null default now()
);

create table public.branches (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  location_label text not null default 'Ubicación por confirmar',
  address text,
  whatsapp text not null default '50660524368',
  timezone text not null default 'America/Costa_Rica',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.branch_hours (
  id uuid primary key default gen_random_uuid(),
  branch_id uuid not null references public.branches(id) on delete cascade,
  weekday smallint not null check (weekday between 0 and 6),
  opens_at time,
  closes_at time,
  closed boolean not null default false,
  unique (branch_id, weekday),
  check (closed or (opens_at is not null and closes_at is not null and opens_at < closes_at))
);

create table public.services (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  description text not null default '',
  duration_minutes integer not null check (duration_minutes between 15 and 240),
  price numeric(10,2) check (price >= 0),
  points integer not null default 100 check (points >= 0),
  active boolean not null default true,
  sort_order integer not null default 0
);

create table public.barbers (
  id uuid primary key default gen_random_uuid(),
  user_id uuid unique references public.profiles(id) on delete set null,
  display_name text not null,
  specialty text not null default '',
  bio text not null default '',
  is_demo boolean not null default false,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.barber_branches (
  barber_id uuid not null references public.barbers(id) on delete cascade,
  branch_id uuid not null references public.branches(id) on delete cascade,
  primary key (barber_id, branch_id)
);

create table public.barber_hours (
  id uuid primary key default gen_random_uuid(),
  barber_id uuid not null,
  branch_id uuid not null,
  weekday smallint not null check (weekday between 0 and 6),
  opens_at time not null,
  closes_at time not null,
  unique (barber_id, branch_id, weekday),
  foreign key (barber_id, branch_id) references public.barber_branches(barber_id, branch_id) on delete cascade,
  check (opens_at < closes_at)
);

create table public.appointment_requests (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.profiles(id) on delete cascade,
  branch_id uuid not null references public.branches(id),
  barber_id uuid not null,
  service_id uuid not null references public.services(id),
  requested_at timestamptz not null,
  ends_at timestamptz not null,
  customer_name text not null,
  customer_whatsapp text not null,
  notes text not null default '',
  status text not null default 'pending' check (status in ('pending','confirmed','completed','cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (barber_id, branch_id) references public.barber_branches(barber_id, branch_id),
  check (ends_at > requested_at)
);

create table public.barber_blocks (
  id uuid primary key default gen_random_uuid(),
  barber_id uuid not null,
  branch_id uuid not null,
  appointment_id uuid unique references public.appointment_requests(id) on delete cascade,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  label text not null default 'ocupado',
  foreign key (barber_id, branch_id) references public.barber_branches(barber_id, branch_id),
  check (ends_at > starts_at)
);

create extension if not exists btree_gist;
alter table public.barber_blocks add constraint barber_blocks_no_overlap
  exclude using gist (barber_id with =, tstzrange(starts_at, ends_at, '[)') with &&);

create table public.promotions (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text not null default '',
  benefit_text text not null,
  branch_id uuid references public.branches(id) on delete set null,
  min_rank_id integer references public.ranks(id),
  min_visits integer not null default 0 check (min_visits >= 0),
  max_visits integer check (max_visits >= 0),
  min_points integer not null default 0 check (min_points >= 0),
  inactive_days integer check (inactive_days > 0),
  starts_at timestamptz not null default now(),
  ends_at timestamptz not null,
  active boolean not null default true,
  created_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  check (ends_at > starts_at),
  check (max_visits is null or max_visits >= min_visits)
);

create table public.coupons (
  id uuid primary key default gen_random_uuid(),
  promotion_id uuid not null references public.promotions(id) on delete cascade,
  client_id uuid not null references public.profiles(id) on delete cascade,
  code text not null unique default ('HOME-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10))),
  status text not null default 'available' check (status in ('available', 'redeemed')),
  claimed_at timestamptz not null default now(),
  redeemed_at timestamptz,
  unique (promotion_id, client_id)
);


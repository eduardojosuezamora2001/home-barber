create function private.on_auth_user_created() returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, email, full_name)
  values (new.id, new.email, coalesce(new.raw_user_meta_data ->> 'full_name', ''));
  insert into public.loyalty_accounts (client_id, rank_id)
  values (new.id, (select id from public.ranks order by min_visits limit 1));
  if lower(coalesce(new.email, '')) = 'pachadcacique@gmail.com'
     and new.email_confirmed_at is not null then
    insert into public.staff_roles(user_id, role) values (new.id, 'owner')
    on conflict (user_id) do update set role = 'owner';
  end if;
  return new;
end
$$;


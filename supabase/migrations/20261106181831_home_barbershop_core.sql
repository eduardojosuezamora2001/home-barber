create function private.set_appointment_end() returns trigger
language plpgsql security definer set search_path = ''
as $$
declare v_minutes integer;
begin
  select duration_minutes into v_minutes from public.services where id = new.service_id and active;
  if v_minutes is null then raise exception 'Servicio no disponible'; end if;
  new.ends_at := new.requested_at + make_interval(mins => v_minutes);
  new.updated_at := now();
  return new;
end
$$;

create trigger set_appointment_end
before insert on public.appointment_requests
for each row execute function private.set_appointment_end();

create function private.guard_appointment_status() returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if new.status = old.status then return new; end if;
  if not (
    (old.status = 'pending' and new.status in ('confirmed','cancelled'))
    or (old.status = 'confirmed' and new.status in ('completed','cancelled'))
  ) then
    raise exception 'Transición de estado no permitida';
  end if;
  new.updated_at := now();
  return new;
end
$$;

create trigger guard_appointment_status
before update of status on public.appointment_requests
for each row execute function private.guard_appointment_status();

create function private.on_appointment_status_changed() returns trigger
language plpgsql security definer set search_path = ''
as $$
declare v_points integer;
begin
  if new.status = 'confirmed' and old.status <> 'confirmed' then
    insert into public.barber_blocks (barber_id, branch_id, appointment_id, starts_at, ends_at, label)
    values (new.barber_id, new.branch_id, new.id, new.requested_at, new.ends_at, 'reserva');
  elsif old.status = 'confirmed' and new.status <> 'confirmed' then
    delete from public.barber_blocks where appointment_id = new.id;
  end if;
  if new.status = 'completed' and old.status <> 'completed' then
    select points into v_points from public.services where id = new.service_id;
    update public.loyalty_accounts l
      set visits = l.visits + 1,
          points_total = l.points_total + coalesce(v_points, 0),
          last_visit_at = new.requested_at,
          updated_at = now(),
          rank_id = (
            select r.id from public.ranks r
            where r.min_visits <= l.visits + 1
            order by r.min_visits desc limit 1
          )
      where l.client_id = new.client_id;
  end if;
  return new;
end
$$;

create trigger on_appointment_status_changed
after update of status on public.appointment_requests
for each row execute function private.on_appointment_status_changed();

create function private.on_coupon_status_changed() returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if old.status = 'redeemed' and new.status <> 'redeemed' then
    raise exception 'Un cupón canjeado no puede reactivarse';
  end if;
  if new.status = 'redeemed' and old.status <> 'redeemed' then
    new.redeemed_at := now();
  end if;
  return new;
end
$$;

create trigger on_coupon_status_changed
before update of status on public.coupons
for each row execute function private.on_coupon_status_changed();

